import { Link } from 'react-router-dom';
import { useQuery } from '@tanstack/react-query';
import { Eye, Download } from 'lucide-react';
import toast from 'react-hot-toast';
import api from '../api/axiosInstance';

interface ReportDTO {
  id: number;
  analysisId: number;
  patientId: number;
  patientName: string;
  patientCin: string | null;
  diagnosis: string | null;
  generatedByName: string;
  reportNumber: number;
  fileName: string;
  createdAt: string;
}

const DIAG_BADGE: Record<string, string> = {
  CONTROL:       'bg-green-100 text-green-700',
  SCHIZOPHRENIA: 'bg-red-100 text-red-700',
  BIPOLAR:       'bg-orange-100 text-orange-700',
  ADHD:          'bg-blue-100 text-blue-700',
};

function formatDate(s: string): string {
  return new Date(s).toLocaleDateString('fr-FR', { day: '2-digit', month: 'short', year: 'numeric' });
}

async function downloadPdf(id: number, fileName: string) {
  try {
    const { data: blob } = await api.get(`/api/reports/${id}/download`, { responseType: 'blob' });
    const url = URL.createObjectURL(blob);
    const a   = document.createElement('a');
    a.href = url; a.download = fileName; a.click();
    URL.revokeObjectURL(url);
  } catch {
    toast.error('Download failed');
  }
}

export default function ReportsPage() {
  const { data: reports = [], isLoading } = useQuery<ReportDTO[]>({
    queryKey: ['reports'],
    queryFn: () => api.get('/api/reports').then(r => r.data),
  });

  return (
    <div className="p-8">

      {/* Header */}
      <div className="mb-6">
        <h1 className="text-2xl font-bold text-gray-900">Reports</h1>
        <p className="mt-1 text-sm text-gray-500">Generated PDF medical reports</p>
      </div>

      {/* Table */}
      <div className="bg-white rounded-xl border border-gray-100 shadow-sm overflow-hidden">
        <table className="w-full text-sm">
          <thead>
            <tr className="border-b border-gray-100 bg-gray-50/60">
              <th className="px-5 py-3.5 text-left text-xs font-semibold uppercase tracking-wider text-gray-400">Report</th>
              <th className="px-5 py-3.5 text-left text-xs font-semibold uppercase tracking-wider text-gray-400">Patient</th>
              <th className="px-5 py-3.5 text-left text-xs font-semibold uppercase tracking-wider text-gray-400">Diagnosis</th>
              <th className="px-5 py-3.5 text-left text-xs font-semibold uppercase tracking-wider text-gray-400">Generated By</th>
              <th className="px-5 py-3.5 text-left text-xs font-semibold uppercase tracking-wider text-gray-400">Date</th>
              <th className="px-5 py-3.5" />
            </tr>
          </thead>
          <tbody className="divide-y divide-gray-50">
            {isLoading && (
              <tr>
                <td colSpan={6} className="px-5 py-12 text-center text-sm text-gray-400">Loading…</td>
              </tr>
            )}
            {!isLoading && reports.length === 0 && (
              <tr>
                <td colSpan={6} className="px-5 py-12 text-center text-sm text-gray-400">No reports yet</td>
              </tr>
            )}
            {reports.map(r => (
              <tr key={r.id} className="hover:bg-slate-50 transition-colors">
                <td className="px-5 py-4">
                  <span className="text-sm font-medium text-gray-700">{r.fileName.replace('.pdf', '')}</span>
                </td>
                <td className="px-5 py-4">
                  <Link to={`/patients/${r.patientId}`} className="font-medium text-gray-900 hover:text-blue-600">
                    {r.patientName}
                  </Link>
                  {r.patientCin && <p className="text-xs text-gray-400 mt-0.5">{r.patientCin}</p>}
                </td>
                <td className="px-5 py-4">
                  {r.diagnosis ? (
                    <span className={`inline-block rounded-full px-2.5 py-0.5 text-xs font-semibold ${DIAG_BADGE[r.diagnosis] ?? 'bg-gray-100 text-gray-600'}`}>
                      {r.diagnosis}
                    </span>
                  ) : <span className="text-gray-400">—</span>}
                </td>
                <td className="px-5 py-4 text-gray-600">{r.generatedByName}</td>
                <td className="px-5 py-4 text-gray-600">{formatDate(r.createdAt)}</td>
                <td className="px-5 py-4">
                  <div className="flex items-center justify-end gap-1">
                    <Link
                      to={`/reports/${r.id}`}
                      className="p-1.5 rounded-lg text-gray-400 hover:bg-blue-50 hover:text-blue-600 transition-colors"
                      title="View"
                    >
                      <Eye className="w-4 h-4" />
                    </Link>
                    <button
                      onClick={() => downloadPdf(r.id, r.fileName)}
                      className="p-1.5 rounded-lg text-gray-400 hover:bg-gray-100 hover:text-gray-700 transition-colors"
                      title="Download"
                    >
                      <Download className="w-4 h-4" />
                    </button>
                  </div>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>

    </div>
  );
}
